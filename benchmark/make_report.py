"""
Build RESULTS.md (all benchmark tables) from the result JSONs, so no number is copied by hand.

  python benchmark/make_report.py      # -> benchmark/RESULTS.md
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
DATA = f"{HERE}/data"
M = ["ndcg@10", "recall@10", "recall@100", "mrr@10", "p@1"]
OURS = ("MedCPT", "Hybrid", "LLM-QE", "Stage1")


def load(p):
    return json.load(open(p))


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def fmt(x):
    return f"{x:.3f}"


def retrieval_rows(named):
    best = {m: max(v[m] for _, v in named) for m in M}
    rows = []
    for name, v in named:
        cells = [f"**{fmt(v[m])}**" if abs(v[m] - best[m]) < 1e-9 else fmt(v[m]) for m in M]
        rows.append([name] + cells)
    return rows


def scifact_retrieval():
    from run_benchmark import load_data
    from run_llm_benchmark import evaluate
    _, _, qrels = load_data()
    R = lambda n: evaluate({q: v for q, v in load(f"{DATA}/baseline_runs/{n}.json").items()}, qrels)
    first = [("BM25", "BM25"), ("SPLADE", "SPLADE"), ("e5-large-v2", "e5-large-v2"),
             ("MedCPT dense *(ours)*", "MedCPT dense"), ("bge-large-en-v1.5", "bge-large-en-v1.5"),
             ("Qwen3-Embedding-4B", "Qwen3-Embedding-4B")]
    rows1 = [(a, R(b)) for a, b in first]
    hyb = load(f"{HERE}/results_baselines_retrieval.json")["results"]
    rows1.append(("Hybrid RRF(BM25, MedCPT dense) *(ours)*", hyb["Hybrid RRF (BM25 + MedCPT dense)"]))
    rr = []
    for n, label in [("MiniLM-L12", "ms-marco-MiniLM-L-12"), ("bge-reranker-v2-m3", "bge-reranker-v2-m3"),
                     ("monoT5-3B", "monoT5-3B"), ("MedCPT", "MedCPT cross-encoder *(ours)*"),
                     ("Qwen3-Reranker-4B", "Qwen3-Reranker-4B")]:
        rr.append((label, hyb[f"Hybrid top-100 -> {n}"], hyb[f"BM25 top-100 -> {n}"]["ndcg@10"]))
    llm = load(f"{HERE}/results_llm.json")["retrieval"]
    llmq = load(f"{HERE}/results_llm_qwen3-8b.json")["retrieval"]
    rows3 = []
    for tag, src in [("claude-haiku-5.5", llm), ("deepseek-v4.1-flash-1017", llm), ("qwen3-8b", llmq)]:
        rows3.append((f"Stage 1 LLM-QE -> BM25 [{tag}]", src[f"BM25 + Stage1 LLM-QE [{tag}]"]))
        rows3.append((f"Stage 1 LLM-QE -> BM25 -> MedCPT [{tag}]", src[f"BM25 + Stage1 LLM-QE + rerank [{tag}]"]))
    return rows1, rr, rows3


def scifact_open_retrieval():
    r = load(f"{HERE}/results_scifact_open.json")["retrieval"]
    first = [("BM25 (Lucene)", "BM25"), ("MedCPT dense *(ours)*", "MedCPT dense"), ("e5-large-v2", "e5-large-v2"),
             ("Qwen3-Embedding-4B", "Qwen3-Embedding-4B"), ("bge-large-en-v1.5", "bge-large-en-v1.5"),
             ("Hybrid RRF(BM25, MedCPT dense) *(ours)*", "Hybrid")]
    rr = [(lab, r[f"Hybrid + {n}"]) for n, lab in [("MiniLM-L12", "ms-marco-MiniLM-L-12"),
                                                    ("bge-reranker-v2-m3", "bge-reranker-v2-m3"),
                                                    ("MedCPT", "MedCPT cross-encoder *(ours)*"),
                                                    ("monoT5-3B", "monoT5-3B"),
                                                    ("Qwen3-Reranker-4B", "Qwen3-Reranker-4B")]]
    llm = []
    for tag in ["claude-haiku-5.5", "deepseek-v4.1-flash-1017", "qwen3-8b"]:
        llm.append((f"Stage 1 LLM-QE -> BM25 [{tag}]", r[f"LLM-QE [{tag}]"]))
        llm.append((f"Stage 1 LLM-QE -> BM25 -> MedCPT [{tag}]", r[f"LLM-QE + MedCPT [{tag}]"]))
    return [(a, r[b]) for a, b in first], rr, llm


def main():
    L = []
    w = L.append
    w("# Benchmark results\n")
    w("Generated by `make_report.py` from the result JSONs in this folder. Bold = best in column within a table.\n")

    # ---------------- SciFact retrieval
    f1, rr, llm = scifact_retrieval()
    w("## 1. SciFact (BEIR test: 300 claims, 5,183 abstracts)\n")
    w("### 1a. First-stage retrieval (whole corpus)\n")
    w(table(retrieval_rows(f1), ["System", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1"]) + "\n")
    w("### 1b. Rerankers on identical candidates (Hybrid top-100; last column: BM25 top-100)\n")
    rows = retrieval_rows([(a, v) for a, v, _ in rr])
    bm = max(x for _, _, x in rr)
    for r_, (_, _, x) in zip(rows, rr):
        r_.append(f"**{fmt(x)}**" if abs(x - bm) < 1e-9 else fmt(x))
    w(table(rows, ["Reranker", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1", "nDCG@10 (BM25 cand.)"]) + "\n")
    w("### 1c. Pipeline with Stage 1 LLM query expansion\n")
    w(table(retrieval_rows(llm), ["System", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1"]) + "\n")

    # ---------------- SciFact verdict
    v = load(f"{HERE}/results_baselines_verdict.json")
    w("### 1d. Verdict (SUPPORT / CONTRADICT / NEI), SciFact official abstract-level metrics\n")
    w(f"Oracle = claim + its cited abstract(s) ({v['n_oracle_pairs']} pairs). "
      f"Open = {v['open_input']} ({v['n_open_pairs']} pairs), identical for every verifier.\n")
    rows = []
    for k, r in v["results"].items():
        o, a, p = r["oracle_3class"], r["oracle_abstract_level"], r["open_abstract_level"]
        rows.append([k.replace("CONTAMINATED", "contaminated, not comparable"), fmt(o["accuracy"]), fmt(o["macro_f1"]),
                     fmt(a["label_only"]["F1"]), fmt(a["rationale_selected"]["F1"]),
                     f"{fmt(p['label_only']['F1'])} ({fmt(p['label_only']['P'])} / {fmt(p['label_only']['R'])})",
                     fmt(p["rationale_selected"]["F1"])])
    w(table(rows, ["Verifier", "Oracle acc", "Oracle macro-F1", "Oracle label F1", "Oracle rationale F1",
                   "Open label F1 (P / R)", "Open rationale F1"]) + "\n")

    # ---------------- SciFact-Open
    f1, rr, llm = scifact_open_retrieval()
    so = load(f"{HERE}/results_scifact_open.json")
    w(f"## 2. SciFact-Open ({so['n_claims']} SciFact test claims, {so['corpus_size']:,} S2ORC abstracts; "
      f"retrieval metrics over the {so['n_eval_claims']} claims with evidence)\n")
    w("### 2a. First-stage retrieval\n")
    w(table(retrieval_rows(f1), ["System", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1"]) + "\n")
    w("### 2b. Rerankers on Hybrid top-100\n")
    w(table(retrieval_rows(rr), ["Reranker", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1"]) + "\n")
    w("### 2c. Pipeline with Stage 1 LLM query expansion\n")
    w(table(retrieval_rows(llm), ["System", "nDCG@10", "R@10", "R@100", "MRR@10", "P@1"]) + "\n")
    w("### 2d. Verdict\n")
    w("Evidence-pair accuracy = label accuracy on the 460 gold evidence abstracts (all SUPPORT/CONTRADICT). "
      "Open = top-3 of Hybrid + MedCPT for every verifier; abstract-level label-only P/R/F1 (unannotated "
      "abstracts count as NEI, as in the SciFact-Open evaluation).\n")
    rows = []
    for k, r in so["verdict"].items():
        p = r["open_abstract_level"]["label_only"]
        rows.append([k, fmt(r["oracle"]["accuracy"]), f"{fmt(p['F1'])} ({fmt(p['P'])} / {fmt(p['R'])})"])
    w(table(rows, ["Verifier", "Evidence-pair acc", "Open label F1 (P / R)"]) + "\n")

    # ---------------- HealthVer
    hv = load(f"{HERE}/results_healthver.json")["verdict"]
    n = next(iter(hv.values()))["oracle"]["n"]
    w(f"## 3. HealthVer (test split: 230 COVID health claims, {n} claim-abstract pairs) — verdict only\n")
    rows = []
    for k, r in hv.items():
        o, a = r["oracle"], r["oracle_abstract_level"]
        rows.append([k, fmt(o["accuracy"]), fmt(o["macro_f1"]),
                     f"{fmt(a['label_only']['F1'])} ({fmt(a['label_only']['P'])} / {fmt(a['label_only']['R'])})",
                     fmt(a["rationale_selected"]["F1"])])
    w(table(rows, ["Verifier", "3-class acc", "3-class macro-F1", "Label F1 (P / R)", "Rationale F1"]) + "\n")

    open(f"{HERE}/RESULTS.md", "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
